// (guide.test.ts เทียบแบบตัวต่อตัว) หัวข้อ `## ส่วนที่ 1` และเส้นคั่นท้าย
// ไม่รวมอยู่ในนี้ สคริปต์ sync เป็นคนวางกรอบ
export function renderGuideMarkdown(sections: GuideSection[] = GUIDE_SECTIONS): string {
  return sections
    .map((s, i) => {
      const heading = `### 1.${i + 1} ${s.title}`
      const steps = s.steps.map((step, j) => `${j + 1}. ${step}`).join('\n')
      return `${heading}\n\n${steps}`
    })
    .join('\n\n')
}
