# โค้ดอ่านจากโฟลเดอร์งาน (= v1.1.1) ตัดเฉพาะบรรทัดว่าง คอมเมนต์ที่ย่อแล้วคงไว้
# ช่วงที่ข้ามแทนด้วย "..." — ไม่มีการแก้ไขโค้ดแม้แต่ตัวอักษรเดียว
import io, re, subprocess, sys
import os
ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..'))
DRAFT = ROOT + '/docs/thesis/2026-10-21-chapter4-draft.md'

def src(f):
    return io.open(ROOT + '/' + f, encoding='utf-8').read().replace('\r\n', '\n').split('\n')

def excerpt(f, ranges):
    L = src(f); out = []; prev = None
    is_comment = lambda s: False  # คอมเมนต์ถูกย่อในซอร์สแล้ว (v1.1.1) จึงคงไว้ในตาราง
    for a, b in ranges:
        kept = [(i, L[i-1]) for i in range(a, b+1) if L[i-1].strip() and not is_comment(L[i-1])]
        if prev is not None and kept and kept[0][0] > prev + 1:
            ind = re.match(r'\s*', kept[0][1]).group(0)
            out.append(ind + '...')
        for i, s in kept:
            # ตัดคอมเมนต์ท้ายบรรทัดที่เป็นภาษาไทยยาวออก (ไม่แตะโค้ด)
            s = re.sub(r'(?<=\S)\s+//\s.*$', '', s) if '//' in s and not re.search(r"['\"`][^'\"`]*//", s) else s
            out.append(s.rstrip())
        if kept: prev = kept[-1][0]
    first, last = ranges[0][0], ranges[-1][1]
    return '\n'.join(out), first, last

N = [6]   # เลขตารางเริ่มที่ 4-6 (4-1..4-3 เครื่องมือ · 4-4 โครงสร้าง · 4-5 ลำดับการพัฒนา)
def code(desc, f, ranges, fn, lang='ts'):
    body, a, b = excerpt(f, ranges)
    n = N[0]; N[0] += 1
    cap = f'ตารางที่ 4-{n} code {desc} (ที่มา: {f}:{a}-{b} ({fn}))'
    return f'{cap}\n\n````{lang}\n{body}\n````\n'

