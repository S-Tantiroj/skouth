// ---------- layout ----------
const COL = [2300, 3003, 3003] // รวม 8306 = A4 ลบขอบซ้าย 1.5" ขวา 1"
const TOTAL = COL.reduce((a, b) => a + b, 0)
const b = { style: BorderStyle.SINGLE, size: 4, color: '000000' }
const borders = { top: b, bottom: b, left: b, right: b }
const margins = { top: 60, bottom: 60, left: 110, right: 110 }

const run = (t, bold = false) => new TextRun({ text: t, font: FONT, size: SIZE, bold })
const para = (t, opts = {}) =>
  new Paragraph({ children: [run(t, opts.bold)], spacing: { before: 0, after: 0 } })

function cell(children, width, extra = {}) {
  return new TableCell({
    borders, margins, width: { size: width, type: WidthType.DXA },
    verticalAlign: VerticalAlign.TOP, children, ...extra,
  })
}
const labelCell = (t, extra = {}) => cell([para(t)], COL[0], extra)
const wide = (paras) => cell(paras, COL[1] + COL[2], { columnSpan: 2 })

// ประมาณจำนวนบรรทัดที่ข้อความใช้ในคอลัมน์ครึ่ง (~30 อักขระต่อบรรทัดที่ 16pt)
const lines = (s) => Math.max(1, Math.ceil([...s.replace(/[ัิ-ฺ็-๎]/g, '')].length / 30))
const blank = () => new Paragraph({ children: [run('')], spacing: { before: 0, after: 0 } })

function flowColumns(flow) {
  const a = [], s = []
  flow.forEach(([who, text], i) => {
    const t = `${i + 1}. ${text}`
    const n = lines(t)
    if (who === 'A') { a.push(para(t)); for (let k = 0; k < n; k++) s.push(blank()) }
    else { s.push(para(t)); for (let k = 0; k < n; k++) a.push(blank()) }
  })
  // ตัดบรรทัดว่างท้ายคอลัมน์ออก
  return [a, s]
}

function ucTable(uc) {
  const [aCol, sCol] = flowColumns(uc.flow)
  return new Table({
    width: { size: TOTAL, type: WidthType.DXA },
    columnWidths: COL,
    rows: [
      new TableRow({ children: [labelCell('Use Case Name'), wide([para(uc.name)])] }),
      new TableRow({ children: [labelCell('Actor'), wide([para(uc.actor)])] }),
      new TableRow({ children: [labelCell('Brief Description'), wide([para(uc.desc)])] }),
      new TableRow({ children: [labelCell('Pre-Conditions'), wide([para(uc.pre)])] }),
      new TableRow({ children: [labelCell('Post Conditions'), wide([para(uc.post)])] }),
      new TableRow({ children: [
        labelCell('Flow of Event', { rowSpan: 2 }),
        cell([para(uc.flowActor)], COL[1]),
        cell([para('System')], COL[2]),
      ] }),
      new TableRow({ children: [cell(aCol, COL[1]), cell(sCol, COL[2])] }),
      new TableRow({ children: [labelCell('Exception'), wide(uc.ex.map((e, i) => para(`${i + 1}. ${e}`)))] }),
    ],
  })
}

const children = []
UC.forEach((uc, i) => {
  const no = FIRST_TABLE_NO + i
  const short = uc.name.split(' (')[0]
  children.push(new Paragraph({
    keepNext: true,
    spacing: { before: i === 0 ? 0 : 360, after: 80 },
    children: [run(`ตารางที่ 3-${no} `, true), run(`Use Case Description: ${short}`)],
  }))
  children.push(ucTable(uc))
})

const doc = new Document({
  styles: { default: { document: { run: { font: FONT, size: SIZE } } } },
  sections: [{
    properties: { page: { margin: { top: 1440, bottom: 1440, left: 2160, right: 1440 } } },
    children,
  }],
})

