-- 023 — เพดานความยาว `profiles.display_name` ที่ชั้นฐานข้อมูล
--
-- **ปิดช่องที่ UAT ST-13 พบ** — ตรวจแล้วสามชั้นเมื่อ 23 ก.ย. 2026 ว่าไม่มีด่าน
-- ความยาวฝั่งเซิร์ฟเวอร์เลยสักชั้น:
--   1. ไม่มี route ใน `app/api` ที่เขียนค่านี้ — `DisplayNameCard` ยิง PostgREST ตรง
--   2. คอลัมน์เป็น `text` ไม่มี `character_maximum_length` และไม่มี CHECK
--   3. migration 019 คืนสิทธิ์ `update (display_name, settings)` ให้ `authenticated`
-- ด่านเดียวที่มีคือ `maxLength` ในฟอร์ม ซึ่งกันการพิมพ์และการวางได้ **แต่กันคำขอ
-- ที่ยิงตรงมาที่ PostgREST ด้วย anon key ซึ่งเป็นค่าสาธารณะไม่ได้**
--
-- **เทียบกับ JB-11 ที่ผ่าน** — สองเคสตรวจเรื่องเดียวกันและหน้าจอทำงานเหมือนกันทุกอย่าง
-- แต่การสร้างตำแหน่งงานผ่าน API route ที่มี `validateJob` ส่วนการบันทึกชื่อเขียนลงฐาน
-- ตรงๆ **การทดสอบผ่านหน้าจออย่างเดียวจึงแยกระบบที่มีด่านกับไม่มีด่านไม่ออก**
--
-- ---------------------------------------------------------------------------
-- ทำไมเพดานเป็น 254 ไม่ใช่ 60 เท่ากับฟอร์ม
-- ---------------------------------------------------------------------------
--
-- **`display_name` ถูกเติมด้วยอีเมลตอนสมัคร** (migration 002):
--
--   insert into public.profiles (id, display_name, role)
--   values (new.id, new.email, 'member')
--
-- ตั้งเพดานเป็น 60 เท่ากับ `DISPLAY_NAME_MAX` แล้ว **คนที่สมัครด้วยอีเมลยาวเกิน 60
-- ตัวจะสมัครไม่ผ่านเลย** เพราะ trigger จะ insert ไม่ได้ — อีเมลตาม RFC 5321 ยาวได้
-- ถึง 254 ตัว · นี่คือความต่างจาก migration 022b ที่ `shortlists.name` มาจากผู้ใช้
-- พิมพ์อย่างเดียว ไม่มีอะไรมาเติมให้อัตโนมัติ
--
-- **เพดานสองชั้นนี้ต่างกันโดยตั้งใจ ห้าม "แก้" ให้ตรงกัน**
--   · 60 (`DISPLAY_NAME_MAX` ใน `lib/auth/identity.ts`) = กฎความเรียบร้อยของหน้าจอ
--     ชื่อที่ยาวกว่านี้ทำให้ตารางผู้ใช้และบันทึกกิจกรรมอ่านยาก
--   · 254 (ที่นี่) = ด่านกันการใช้งานผิดวัตถุประสงค์ เช่นยิงสตริงขนาดเมกะไบต์
--     เข้ามาผ่าน PostgREST ซึ่งเป็นสิ่งที่ฟอร์มกันไม่ได้
-- การยุบสองค่าให้เท่ากันจะพังการสมัครทันทีตามเหตุผลข้างบน
--
-- ---------------------------------------------------------------------------
-- ตรวจก่อนรัน
-- ---------------------------------------------------------------------------
-- `ALTER TABLE ADD CONSTRAINT` ตรวจแถวเดิมด้วย มีแถวผิดแม้แถวเดียว migration ล้มทั้งไฟล์
--
--   select count(*) filter (where char_length(trim(display_name)) > 254),
--          count(*) filter (where char_length(email) > 254)
--   from profiles;
--
-- ยืนยันเมื่อ 2026-10-14: ยาวสุดคือ 33 ตัวทั้งสองคอลัมน์ ไม่มีแถวติด
--
-- ---------------------------------------------------------------------------
-- รายละเอียดของเงื่อนไข
-- ---------------------------------------------------------------------------
-- **เขียน `is null or` ไว้ชัดเจนแทนการพึ่งตรรกะสามค่าของ SQL** — CHECK ที่ได้ผลเป็น
-- NULL ถือว่าผ่านอยู่แล้ว แต่คนอ่านไม่ควรต้องนึกกฎนั้นเองเพื่อจะรู้ว่าตั้งใจให้ NULL ผ่าน
-- ค่า NULL ยอมรับได้เพราะ `identityName` ถอยไปใช้ `email` อยู่แล้ว (migration 021)
--
-- **`trim` อยู่ข้างใน `char_length`** ชื่อที่เป็นช่องว่างล้วนต้องไม่ผ่าน เหมือน 022b
-- แต่ **constraint ไม่ได้ตัดช่องว่างให้** การตัดยังเป็นหน้าที่ของ `normalizeDisplayName`
-- ก่อนส่ง ไม่งั้นชื่อ " ก " จะถูกเก็บพร้อมช่องว่างแล้วเรียงลำดับผิด

alter table profiles add constraint profiles_display_name_len
  check (display_name is null or char_length(trim(display_name)) between 1 and 254);
