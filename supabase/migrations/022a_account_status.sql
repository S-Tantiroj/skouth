-- 022a — สถานะการอนุมัติบัญชี และลบคอลัมน์ที่ไม่มีใครใช้
--
-- **ไฟล์นี้ไม่กระทบเว็บที่ deploy อยู่** โค้ดที่ใช้งานจริงอ่าน `.select('role')`
-- ไม่ได้ดึง `status` และไม่มีที่ไหนอ่าน `note` จึงรันได้ก่อน deploy โดยไม่มีช่วง
-- ที่ฐานข้อมูลเข้มกว่าหน้าจอ · ส่วน constraint ชื่อ shortlist อยู่ใน 022b
-- เพราะกระทบทันทีที่รัน

-- ---------------------------------------------------------------------------
-- 1. สถานะบัญชี
-- ---------------------------------------------------------------------------
-- แยกจาก `role` เป็นคนละคอลัมน์โดยตั้งใจ — "ได้รับอนุมัติหรือยัง" กับ "ทำอะไรได้บ้าง"
-- เป็นคนละคำถาม การยัดค่า pending เข้า enum `user_role` จะทำให้ช่องเลือกสิทธิ์ที่
-- /admin/users มีตัวเลือกที่ไม่มีความหมาย และพออนุมัติแล้วจะไม่เหลือร่องรอยว่า
-- เคยถูกปฏิเสธมาก่อน
create type account_status as enum ('pending', 'approved', 'rejected');

-- ค่าตั้งต้น 'pending' ทำให้บัญชีใหม่รออนุมัติโดยไม่ต้องแก้ trigger
alter table profiles add column status account_status not null default 'pending';

-- ต้องรันหลัง add column: บัญชีเดิมทั้งหมดรวมถึงผู้ดูแลระบบได้รับอนุมัติ
update profiles set status = 'approved';

-- **ไม่เพิ่ม `status` เข้า `grant update` ของ migration 019 โดยตั้งใจ**
-- คอลัมน์ใหม่ไม่ได้สิทธิ์เขียนโดยอัตโนมัติ ซึ่งเป็นพฤติกรรมที่ migration นั้น
-- ออกแบบไว้ ถ้าเผลอเพิ่ม ผู้ใช้ทุกคนจะยิง
-- PATCH /rest/v1/profiles?id=eq.<ตัวเอง> ด้วย {"status":"approved"}
-- เพื่ออนุมัติตัวเองผ่าน anon key ที่เป็นค่าสาธารณะได้ทันที

-- ---------------------------------------------------------------------------
-- 2. ลบคอลัมน์ note
-- ---------------------------------------------------------------------------
-- มีมาตั้งแต่ migration 001 แต่ไม่มีโค้ดไหนอ่านหรือเขียนเลย ยืนยันด้วยการค้นทั้งรีโป
-- การออกแบบรอบนี้ตัดสินแล้วว่าไม่ทำโน้ตต่อผู้สมัคร จึงลบทิ้งแทนที่จะปล่อยไว้ —
-- เล่มมีบท Data Dictionary ที่ต้องอธิบายทุกคอลัมน์ คอลัมน์ที่ไม่มีใครใช้คือคำถาม
-- ที่ตอบยาก
